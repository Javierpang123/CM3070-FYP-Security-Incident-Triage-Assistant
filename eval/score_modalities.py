# Scores per-modality predictions produced by evaluate_modalities.py.

"""
Reads eval/results/modality_predictions.csv and computes, per modality:
    - macro F1 against label.json ground truth (Design 3.7 target: >= 0.70)
    - a full sklearn classification report (precision/recall/F1 per tactic)
    - a confusion matrix
"""

import csv
from collections import defaultdict
from pathlib import Path

from sklearn.metrics import f1_score, confusion_matrix, classification_report

# Directory to store results, including the predictions CSV and the final report
RESULTS_DIR = Path(__file__).resolve().parent / "results"

# Directory to store the predictions CSV generated by evaluate_modalities.py
PREDICTIONS_CSV = RESULTS_DIR / "modality_predictions.csv"

# Directory to store the final report generated by this script, 
# including macro F1, classification report, and confusion matrix
REPORT_PATH = RESULTS_DIR / "modality_f1_report.txt"

# F1-score target more than 0.70 per model
F1_TARGET = 0.70 

# Function to load predictions from the CSV file generated by evaluate_modalities.py
def load_predictions() -> list:
    with open(PREDICTIONS_CSV, "r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))

# Main scoring function that computes macro F1, classification report, 
# and confusion matrix for each modality
def main():
    
    # Check if the predictions CSV exists; if not, raise an error
    if not PREDICTIONS_CSV.exists():
        raise FileNotFoundError(f"{PREDICTIONS_CSV} not found - run evaluate_modalities.py first.")

    # Store predictions by modality for later evaluation
    rows = load_predictions()
    by_modality = defaultdict(list)
    
    # Loop through each row in the predictions and group them by modality
    for row in rows:
        by_modality[row["modality"]].append(row)

    # Holder for the report lines that will be printed and saved to a file
    report_lines = []
    
    # Loop through each modality and compute macro F1, classification report, and confusion matrix
    for modality, modality_rows in sorted(by_modality.items()):
        y_true = [row["tactic_actual"] for row in modality_rows]
        y_pred = [row["tactic_predicted"] for row in modality_rows]

        labels = sorted(set(y_true) | set(y_pred))
        macro_f1 = f1_score(y_true, y_pred, labels=labels, average="macro", zero_division=0)
        cm = confusion_matrix(y_true, y_pred, labels=labels)

        report_lines.append(f"=== {modality.upper()} modality ===")
        report_lines.append(f"n = {len(modality_rows)} incidents")
        report_lines.append(f"Macro F1: {macro_f1:.4f}")
        report_lines.append(f"Design 3.7 target: F1 >= {F1_TARGET:.2f}")
        report_lines.append(f"Target met: {'YES' if macro_f1 >= F1_TARGET else 'NO'}")
        report_lines.append("")
        report_lines.append(classification_report(y_true, y_pred, labels=labels, zero_division=0))
        report_lines.append("Confusion matrix (rows = true tactic, cols = predicted tactic):")
        report_lines.append("Labels: " + ", ".join(labels))
        for label, cm_row in zip(labels, cm):
            report_lines.append(f"  {label}: {cm_row.tolist()}")
        report_lines.append("")

    # Write the report to a text file and print it to the console
    report_text = "\n".join(report_lines)
    print(report_text)

    # Write the report to a text file for later reference
    REPORT_PATH.write_text(report_text, encoding="utf-8")
    
    # Print the path to the report file for reference to know where file is saved
    print(f"\nFull report written to {REPORT_PATH}")

# Run main function if this file is run directly
if __name__ == "__main__":
    main()
